// Five CEO design decisions (per the Kelly collaborative session):
//   1. Confidence → probability via tier-based calibration table from
//      pick_history actual win rates (NOT confidence/100, which would
//      assume the algorithm is calibrated).
//   2. Quarter Kelly (0.25 fraction) — conservative starting point.
//      Revisit after 500+ resolved bets.
//   3. Manual bankroll setting in Settings — CEO updates as desired.
//      No auto-tracking from `bets` table (avoid coupling sizing to
//      the C17 bet-tracking architecture concerns).
//   4. Per-bet cap: 5% of bankroll, hard ceiling regardless of edge.
//   5. Rounding: nearest $5.
//
// §19.3 note: future updates to PROBABILITY_BY_CONFIDENCE are
